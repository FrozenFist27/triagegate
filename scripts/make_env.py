"""Create <project>/.env by copying ONLY the keys this project needs from
C:/Users/Sambudh/upwork-portfolio/secrets.env.

Values are never printed, logged or echoed. Run:  python scripts/make_env.py
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
SECRETS = Path(r"C:/Users/Sambudh/upwork-portfolio/secrets.env")
OUT = PROJECT_ROOT / ".env"

# Keys this project needs (everything else in secrets.env is ignored).
NEEDED = [
    "ANTHROPIC_API_KEY",
    "LLM_PROVIDER",
    "LLM_MODEL",
    "SLACK_BOT_TOKEN",
    "SLACK_SIGNING_SECRET",
    "SLACK_APPROVAL_CHANNEL_ID",
    "HUBSPOT_SERVICE_KEY",
    "IMAP_USER",
    "IMAP_APP_PASSWORD",
]

# Local-only keys generated here (not in secrets.env).
LOCAL_DEFAULTS = {
    "LLM_MAX_ATTEMPTS": "3",
    "LLM_FAULT_INJECTION": "off",
    "LLM_PRICE_IN_PER_MTOK": "0.10",
    "LLM_PRICE_OUT_PER_MTOK": "0.50",
    "APPROVAL_TTL_MINUTES": "1440",
    "DB_PATH": "data/triagegate.db",
    "IMAP_HOST": "imap.gmail.com",
}


def parse_secrets(path: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        out[key.strip()] = value.strip().strip('"').strip("'")
    return out


def random_token(n: int = 32) -> str:
    import secrets

    return secrets.token_urlsafe(n)


def main() -> int:
    if not SECRETS.exists():
        print(f"ERROR: secrets file not found: {SECRETS}", file=sys.stderr)
        return 1

    secrets_map = parse_secrets(SECRETS)
    missing = [k for k in NEEDED if not secrets_map.get(k)]
    if missing:
        print(f"ERROR: missing keys in secrets.env: {', '.join(missing)}", file=sys.stderr)
        return 1

    lines: list[str] = [
        "# Auto-generated by scripts/make_env.py - DO NOT COMMIT.",
        "# Values copied from the private secrets.env (names not printed).",
        "",
        "# --- LLM ---",
        f"LLM_PROVIDER={secrets_map.get('LLM_PROVIDER') or 'anthropic'}",
        f"LLM_MODEL={secrets_map.get('LLM_MODEL') or 'claude-haiku-5-5'}",
        f"ANTHROPIC_API_KEY={secrets_map['ANTHROPIC_API_KEY']}",
        f"LLM_MAX_ATTEMPTS={LOCAL_DEFAULTS['LLM_MAX_ATTEMPTS']}",
        f"LLM_FAULT_INJECTION={LOCAL_DEFAULTS['LLM_FAULT_INJECTION']}",
        f"LLM_PRICE_IN_PER_MTOK={LOCAL_DEFAULTS['LLM_PRICE_IN_PER_MTOK']}",
        f"LLM_PRICE_OUT_PER_MTOK={LOCAL_DEFAULTS['LLM_PRICE_OUT_PER_MTOK']}",
        "",
        "# --- Internal auth ---",
        f"TRIAGE_API_TOKEN={random_token()}",
        f"N8N_INGEST_TOKEN={random_token()}",
        f"N8N_ENCRYPTION_KEY={random_token()}",
        "",
        "# --- Approvals / storage ---",
        f"APPROVAL_TTL_MINUTES={LOCAL_DEFAULTS['APPROVAL_TTL_MINUTES']}",
        f"DB_PATH={LOCAL_DEFAULTS['DB_PATH']}",
        "",
        "# --- n8n ---",
        "N8N_PUBLIC_URL=",
        "",
        "# --- Slack ---",
        f"SLACK_BOT_TOKEN={secrets_map['SLACK_BOT_TOKEN']}",
        f"SLACK_SIGNING_SECRET={secrets_map['SLACK_SIGNING_SECRET']}",
        f"SLACK_APPROVAL_CHANNEL_ID={secrets_map['SLACK_APPROVAL_CHANNEL_ID']}",
        "",
        "# --- HubSpot ---",
        f"HUBSPOT_SERVICE_KEY={secrets_map['HUBSPOT_SERVICE_KEY']}",
        "",
        "# --- IMAP test inbox ---",
        f"IMAP_HOST={LOCAL_DEFAULTS['IMAP_HOST']}",
        f"IMAP_USER={secrets_map['IMAP_USER']}",
        f"IMAP_APP_PASSWORD={secrets_map['IMAP_APP_PASSWORD']}",
        "",
    ]

    OUT.write_text("\n".join(lines), encoding="utf-8")
    try:
        os.chmod(OUT, 0o600)
    except OSError:
        pass
    print(f"Wrote {OUT} ({len(NEEDED)} secret keys copied; values not shown).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
